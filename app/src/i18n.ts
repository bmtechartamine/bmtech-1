export type Key = keyof Dict;

const LANG_KEY = 'bmtplan.lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'fr' || saved === 'en') return saved;
  } catch {
    /* storage blocked: fall through */
  }
  return typeof navigator !== 'undefined' && navigator.language?.startsWith('en') ? 'en' : 'fr';
}

let lang: Lang = initialLang();

export function getLang(): Lang {
  return lang;
}

export function setLang(l: Lang) {
  lang = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    /* ignore */
  }
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = (lang === 'en' ? en : fr)[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** "1 pièce", "3 pièces"; French treats 0 as singular too. */
export function count(n: number, one: Key, many: Key): string {
  const singular = lang === 'fr' ? n <= 1 : n === 1;
  return `${n} ${t(singular ? one : many)}`;
}

export const catLabel = (id: CategoryId) => t(`cat_${id}` as Key);
